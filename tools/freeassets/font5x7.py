def glyph(ch):
    """The seven rows for ch, or None for a character the font lacks.
    Lowercase is the capital squeezed into the lower five rows."""
    if ch in GLYPHS:
        return GLYPHS[ch]
    if "a" <= ch <= "z":
        big = GLYPHS[ch.upper()]
        return (0x00, 0x00, big[0], big[2], big[3], big[4], big[6])
    return None
